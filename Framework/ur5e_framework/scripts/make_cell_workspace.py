"""Write the shared workspace files that cover the WHOLE lab cell — INSTRUCTOR tool.

STATUS: internal (not synced). No robot needed.

    python scripts/make_cell_workspace.py            -> workspaces/cart_360_real.json
                                                        workspaces/cart_360_sim.json

A taught workspace.json is a group's own box. These two files are the same
thing for everybody: a workspace whose box IS the cell `cart_360` (the TCP box
of the cell profile), with a common home pose above the cart top. A script
built on the template skeleton (Workspace.load + Robot(profile=ws) +
move_joints(ws.home_joints)) then runs with absolute poses anywhere in the
cell; the cart / handle / floor checks of the cell apply as always.

Not for fractions: ws.pose(u, v, w) / ws.grid / ws.line spread over a box of
almost 2 x 2 x 1.75 m, most of which the arm cannot reach — use absolute poses
with these files, or teach an own workspace for area work.

Two files because a workspace is tied to where it is used (a 'sim' file is
refused on the real arm and vice versa); the content is identical.
Re-run after the cell geometry changed (teach_cart_cell.py).
"""

from __future__ import annotations

import math
import sys
import types
from pathlib import Path

try:
    import rtde_control  # noqa: F401
except ImportError:                       # runs without ur_rtde too
    for _name, _cls in (("rtde_control", "RTDEControlInterface"), ("rtde_receive", "RTDEReceiveInterface"),
                        ("rtde_io", "RTDEIOInterface")):
        _m = types.ModuleType(_name)
        setattr(_m, _cls, type(_cls, (), {}))
        sys.modules[_name] = _m

from ur5e import kinematics as kin                      # noqa: E402
from ur5e.safety import get_profile                     # noqa: E402
from ur5e.workspace import Workspace                    # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "workspaces"
CELL = "cart_360"

# Common home: the pose taught as home on the lab arm on 2026-10-29 (above the
# cart top in front of the robot, tool pointing down). Joint angles in degrees.
HOME_JOINTS_DEG = [-137.9, -72.5, -94.7, -95.5, 92.0, -128.1]


def main() -> None:
    cell = get_profile(CELL)
    b = cell.workspace
    q_home = [math.radians(v) for v in HOME_JOINTS_DEG]
    cell.check_arm(q_home, None, what="home")            # raises if home is not clear of the cart
    T = kin.fk_frames(q_home)[-1]
    home = [*(float(v) for v in T[:3, 3]), *(float(v) for v in kin.matrix_to_rotvec(T[:3, :3]))]
    rot = home[3:6]
    xy = [(b.x[0], b.y[0]), (b.x[1], b.y[0]), (b.x[1], b.y[1]), (b.x[0], b.y[1])]
    low = [[x, y, b.z[0], *rot] for x, y in xy]
    high = [[x, y, b.z[1], *rot] for x, y in xy]
    OUT.mkdir(exist_ok=True)
    for target in ("real", "sim"):
        ws = Workspace.from_points(
            target, low, high, home, q_home,
            note=(f"SHARED workspace = the whole lab cell '{CELL}' (generated by scripts/make_cell_workspace.py, "
                  f"not taught). Use absolute poses; fractions (ws.pose/grid/line) are not meaningful here. "
                  f"Home = the lab home above the cart top, tool down."))
        path = ws.save(OUT / f"{CELL}_{target}.json")
        print(f"written {path.relative_to(ROOT)}")
    print(f"\nbox  x {b.x[0]:+.3f}..{b.x[1]:+.3f}  y {b.y[0]:+.3f}..{b.y[1]:+.3f}  z {b.z[0]:+.3f}..{b.z[1]:+.3f} m"
          f"\nhome flange at x {home[0]:+.3f}  y {home[1]:+.3f}  z {home[2]:+.3f} m, joints {HOME_JOINTS_DEG} deg")


if __name__ == "__main__":
    main()
